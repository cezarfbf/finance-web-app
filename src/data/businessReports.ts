/** Sorted newest-first. Useful for the Business landing grid. */
export function listBusinessReports(): MonthlyReport[] {
  return [...businessReports].sort(
    (a, b) => b.year - a.year || b.month - a.month,
  );
}

export function findBusinessReport(
  year: number,
  month: number,
): MonthlyReport | undefined {
  return businessReports.find((r) => r.year === year && r.month === month);
}

/** Distinct years that have at least one report — used to drive year filters. */
export function listBusinessYears(): number[] {
  return Array.from(new Set(businessReports.map((r) => r.year))).sort(
    (a, b) => b - a,
  );
}
